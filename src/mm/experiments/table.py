"""Phase 8 results table (test period) from the runner's outputs (D042).

Writes reports/phase8_results.md and reports/figures/phase8_paired_diffs.png. The
hand-written mechanism sentences live in reports/phase8_mechanisms.md and are appended.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
import yaml  # noqa: E402

from mm.config import load_config  # noqa: E402
from mm.data.db import connect  # noqa: E402
from mm.experiments.metrics import max_drawdown, paired_diff, sharpe, stress_threshold  # noqa: E402

SURFACE, INK, INK2, GRID, AXIS = "#fcfcfb", "#0b0b0b", "#52514e", "#e1e0d9", "#c3c2b7"
BLUE = "#2a78d6"
GROUPS = {
    "spread": ["spread_capture"], "theta": ["theta"], "gamma": ["gamma"], "vega": ["vega"],
    "delta+basis": ["delta", "basis"],
    "hedging+fees": ["hedge_cost", "option_fee", "perp_fee", "delivery_fee"],
    "fund+settle": ["funding", "settlement"],
}  # fmt: skip


def dvol_daily(cfg) -> pd.Series:
    con = connect(cfg.data.clean_dir)
    d = con.execute("select ts, dvol_close from dvol order by ts").df()
    d["day"] = pd.to_datetime(d["ts"], utc=True).dt.date
    return d.groupby("day")["dvol_close"].mean()


def _fmt(v, f="{:,.0f}"):
    return "" if v is None or (isinstance(v, float) and not np.isfinite(v)) else f.format(v)


def _diff(r: dict, is_base: bool) -> str:
    return "" if is_base else f"{r['mean']:+,.0f} ± {r['two_se']:,.0f}"


def _tbl(cols, rows) -> str:
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def write(base_path: str, exp_path: str) -> Path:
    cfg = load_config(base_path)
    exp = yaml.safe_load(Path(exp_path).read_text())
    root = Path(exp["settings"]["out_dir"])
    meta = json.loads((root / "meta.json").read_text())
    names = list(meta["variants"])
    sp = cfg.study_period
    dv = dvol_daily(cfg)
    thr = stress_threshold(dv, sp.start, sp.train_end, exp["settings"]["stress_dvol_quantile"])
    daily = {n: pd.read_parquet(root / "test" / n / "daily_pnl.parquet") for n in names}
    summ = {n: json.loads((root / "test" / n / "summary.json").read_text()) for n in names}
    base = daily["baseline"]["total"]
    stress = pd.Series({d: dv.get(d, np.nan) >= thr for d in base.index})
    n_stress = int(stress.sum())

    main_rows, comp_rows, fig = [], [], []
    for n in names:
        tot = daily[n]["total"]
        s = summ[n]
        pd_all = paired_diff(tot, base)
        pd_calm = paired_diff(tot[~stress], base[~stress])
        pd_str = paired_diff(tot[stress], base[stress])
        fig.append((n, pd_all["mean"], pd_all["two_se"]))
        is_base = n == "baseline"
        main_rows.append([
            f"**{n}**" if n in ("baseline", "best") else n, _fmt(tot.sum()), _fmt(tot.mean()),
            _fmt(sharpe(tot), "{:.2f}"), _fmt(max_drawdown(tot)),
            _fmt(tot[~stress].mean()), _fmt(tot[stress].mean()),
            _diff(pd_all, is_base), _diff(pd_calm, is_base), _diff(pd_str, is_base),
            "" if n == "baseline" else _fmt(pd_all["ac1"], "{:.2f}"),
            f"{s['fills']:,}", f"{s['share_of_contracts'] * 100:.2f}%", f"{s['hedges']:,}",
            _fmt(s["markout_vp"].get("1h", np.nan), "{:+.2f}"),
            f"{s['mean_abs_vega_frac'] * 100:.0f}%",
            f"{s.get('mean_abs_gamma_frac', float('nan')) * 100:.0f}%",
            f"{s['quotes_cut_frac'] * 100:.1f}%",
        ])  # fmt: skip
        comp_rows.append([n] + [_fmt(daily[n][c].sum().sum()) for c in GROUPS.values()]
                         + [_fmt(tot.sum())])  # fmt: skip

    sel_rows = []
    for name, b in meta["best"].items():
        for cand, v in b["train_mean_daily"].items():
            sel_rows.append([name, cand, _fmt(v), "✅" if cand.endswith(f"={b['value']:g}")
                             or (cand == "baseline" and b["value"] == _base_val(cfg, exp, name))
                             else ""])  # fmt: skip

    figs = Path("reports/figures")
    figs.mkdir(parents=True, exist_ok=True)
    fp = figs / "phase8_paired_diffs.png"
    _fig(fig, fp)
    mech = Path("reports/phase8_mechanisms.md")
    md = f"""# Phase 8: experiment results (test period {meta["test"][0]} to {meta["test"][1]})

Generated by `uv run python -m mm.run --config {base_path} --experiments {exp_path}`.
USD. Each variant changes one parameter of the baseline (`config/base.yaml`); "best"
combines the best value of each selectable experiment, chosen on the **training period**
({meta["train"][0]} to {meta["train"][1]}) by mean daily P&L. Paired difference =
mean of daily (variant − baseline) ± 2 standard errors over the {len(base)} test days
(ac1: lag-1 autocorrelation of the daily differences; if large, the error bar is too
narrow). Stress days: daily mean DVOL ≥ {thr:.1f}, the
{exp["settings"]["stress_dvol_quantile"]:.0%} quantile of training days ({n_stress} of
{len(base)} test days).

## Results

{
        _tbl(
            [
                "variant",
                "total",
                "mean/day",
                "Sharpe",
                "max DD",
                "calm/day",
                "stress/day",
                "Δ vs base/day",
                "Δ calm",
                "Δ stress",
                "ac1",
                "fills",
                "vol share",
                "hedges",
                "1h markout (vp)",
                "mean |vega|/limit",
                "quotes cut",
            ],
            main_rows,
        )
    }

## P&L by component (test period totals)

{_tbl(["variant", *GROUPS, "total"], comp_rows)}

## Selection on the training period (mean daily P&L)

{_tbl(["experiment", "candidate", "train mean/day", "chosen"], sel_rows)}

![paired differences]({fp.relative_to("reports")})

{mech.read_text() if mech.exists() else ""}
"""
    out = Path("reports/phase8_results.md")
    out.write_text(md)
    return out


def _base_val(cfg, exp, name):
    x = cfg
    for p in exp["experiments"][name]["param"]:
        x = getattr(x, p)
    return x


def _fig(items, path: Path) -> None:
    items = [i for i in items if i[0] != "baseline"]
    fig, ax = plt.subplots(figsize=(8, 0.35 * len(items) + 1.2), facecolor=SURFACE)
    y = np.arange(len(items))[::-1]
    ax.errorbar([m for _, m, _ in items], y, xerr=[e for *_, e in items], fmt="o",
                color=BLUE, ecolor=BLUE, elinewidth=1.4, capsize=3, markersize=5)  # fmt: skip
    ax.axvline(0, color=AXIS, linewidth=1.0)
    ax.set_yticks(y, [n for n, *_ in items])
    ax.set_facecolor(SURFACE)
    ax.set_title("Daily P&L difference vs baseline, USD (mean ± 2 se, test period)",
                 loc="left", fontsize=10, color=INK)  # fmt: skip
    ax.grid(axis="x", color=GRID, linewidth=0.6)
    for s in ("top", "right", "left"):
        ax.spines[s].set_visible(False)
    ax.tick_params(colors=INK2, labelsize=8, length=0)
    fig.tight_layout()
    fig.savefig(path, dpi=150, facecolor=SURFACE)
    plt.close(fig)
