"""Do Deribit's marks move sticky-moneyness or sticky-strike? (D038 follow-up, D040)

For refits R0 and R1 = R0 + h, and an expiry fitted 'full' at both:
    y = sigma_1(k=0) - sigma_0(k=0)           change in ATM vol
    x = sigma_0'(k=0) x ln(F1/F0)             what sticky strike predicts for y
(under sticky strike the new ATM strike F1 keeps the vol it had at R0, which sat at
k = ln(F1/F0) on the old smile). beta = sum(xy) / sum(x^2):
    beta ~ 0  sticky moneyness (the smile moves with the forward; D038 delta is right)
    beta ~ 1  sticky strike (Black delta would be right)
beta also absorbs any spot-vol correlation beyond the skew, so it is the slope that a
minimum-variance hedge would use. Non-overlapping pairs; standard error from residuals.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from mm.sim.fair import _ms


def _sig(a, b, rho, m, s, tref, k):
    x = k - m
    return np.sqrt(np.maximum(a + b * (rho * x + np.sqrt(x * x + s * s)), 0.0) / tref)


def _dsig(a, b, rho, m, s, tref, k):
    x = k - m
    return b * (rho + x / np.sqrt(x * x + s * s)) / (2 * _sig(a, b, rho, m, s, tref, k) * tref)


def pairs(fits: pd.DataFrame, curve, h_s: int, min_days: float, max_days: float) -> pd.DataFrame:
    f = fits[fits["kind"] == "full"].copy()
    f["r"] = _ms(f["refit_ts"])
    f["e"] = _ms(f["expiry"])
    f = f[((f["e"] - f["r"]) / 86_400_000).between(min_days, max_days)]
    grid = np.unique(f["r"])
    step = int(h_s * 1000)
    starts = grid[(grid - grid[0]) % step == 0]  # non-overlapping
    a = f[f["r"].isin(starts)]
    b = f.assign(r=f["r"] - step)  # R1 rows keyed by their R0
    j = a.merge(b, on=["r", "e"], suffixes=("0", "1"))
    if j.empty:
        return j
    ts0 = pd.Series(pd.to_datetime(j["r"], unit="ms", utc=True))
    exp = pd.Series(pd.to_datetime(j["e"], unit="ms", utc=True))
    f0 = curve.forwards(ts0, exp, 0, inclusive=True)["forward_usd"].to_numpy()
    f1 = curve.forwards(ts0 + pd.Timedelta(seconds=h_s), exp, 0, inclusive=True)["forward_usd"]
    p0 = [j[c + "0"].to_numpy() for c in ("a", "b", "rho", "m", "s", "t_ref")]
    p1 = [j[c + "1"].to_numpy() for c in ("a", "b", "rho", "m", "s", "t_ref")]
    out = pd.DataFrame({"r0": j["r"], "expiry": j["e"],
                        "y": _sig(*p1, 0.0) - _sig(*p0, 0.0),
                        "skew": _dsig(*p0, 0.0),
                        "dlnf": np.log(f1.to_numpy() / f0)})  # fmt: skip
    out["x"] = out["skew"] * out["dlnf"]
    return out.replace([np.inf, -np.inf], np.nan).dropna()


def beta(p: pd.DataFrame) -> dict:
    x, y = p["x"].to_numpy(), p["y"].to_numpy()
    if len(x) < 3 or not (x * x).sum() > 0:
        return {"n": len(x), "beta": np.nan, "se": np.nan}
    b = float((x * y).sum() / (x * x).sum())
    res = y - b * x
    se = float(np.sqrt((res * res).sum() / (len(x) - 1) / (x * x).sum()))
    return {"n": int(len(x)), "beta": b, "se": se,
            "median_abs_dlnf": float(np.median(np.abs(p["dlnf"])))}  # fmt: skip


def main(argv=None):
    """uv run python -m mm.pnl.smile_dynamics --config config/base.yaml  (training period)"""
    import argparse
    from pathlib import Path

    from mm.config import load_config
    from mm.pricing.enrich import build_curve
    from mm.surface.build import CACHE

    ap = argparse.ArgumentParser(prog="mm.pnl.smile_dynamics")
    ap.add_argument("--config", required=True)
    a = ap.parse_args(argv)
    cfg = load_config(a.config)
    s, e = cfg.study_period.start, cfg.study_period.train_end
    curve = build_curve(cfg, s, e)
    fits = pd.read_parquet(CACHE / "fits.parquet")
    lo, hi = pd.Timestamp(s, tz="UTC"), pd.Timestamp(e, tz="UTC")
    fits = fits[(fits["refit_ts"] >= lo) & (fits["refit_ts"] < hi)]
    rows = []
    for h in (300, 900, 3600, 4 * 3600, 86_400):
        for b0, b1 in ((2, 8), (8, 35), (35, 100)):
            r = beta(pairs(fits, curve, h, b0, b1))
            rows.append({"horizon": f"{h // 60} min" if h < 3600 else f"{h // 3600} h",
                         "days": f"{b0}-{b1}", "pairs": r["n"], "beta": r["beta"],
                         "se": r["se"]})  # fmt: skip
    t = pd.DataFrame(rows)
    lines = ["| horizon | expiry days | pairs | beta | 2 se |", "|---|---|---|---|---|"]
    lines += [f"| {r.horizon} | {r.days} | {r.pairs:,} | {r.beta:.2f} | {2 * r.se:.2f} |"
              for r in t.itertuples()]  # fmt: skip
    md = f"""# Smile dynamics: sticky moneyness or sticky strike? (training period {s} to {e})

Generated by `uv run python -m mm.pnl.smile_dynamics --config {a.config}`.
For refit pairs (R, R + horizon), expiries fitted `full` at both, non-overlapping:
change in ATM vol regressed (through the origin) on skew x ln(F1/F0).
**beta = 0: sticky moneyness** (the D038 hedge delta). **beta = 1: sticky strike**
(Black delta). Above 1: vol moves against spot by more than the skew implies.

{chr(10).join(lines)}
"""
    Path("reports/smile_dynamics.md").write_text(md)
    print(t.to_string(index=False))


if __name__ == "__main__":
    main()
